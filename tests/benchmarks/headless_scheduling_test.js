'use strict'
const assert=require('assert')
const input=require('../../testdata/benchmarks/taian-scheduling-v1.json')
require('./execution_comparison_test')
const {validate,route,commandFor}=require('./headless_scheduling/case')
const {compare,roundtrip}=require('./headless_scheduling/compare')
const {datasetIdentity}=require('./headless_scheduling/records')
const {cameraForPose,verifySnapshot,verifyReferenceCamera}=require('./headless_scheduling/camera')
const {cameraSnapshot}=require('../../sdk/js/camera/terra_camera_snapshot')
const reference=require('../../testdata/benchmarks/taian-oblique-camera-v1.json')
const camera=cameraForPose(reference.pose)
assert(camera.tiltRadians<0,'Public orbit tilt did not use runtime assignment')
verifyReferenceCamera(input,reference.pose,reference.row)
const wrong=cameraSnapshot({transform:'cylindrical',radius:input.radiusMeters},
  {...camera,tiltRadians:-camera.tiltRadians},{...input.viewport,fovRadians:input.verticalFovRadians})
assert.throws(()=>verifySnapshot(input,reference.pose,wrong),/camera differs from the public SDK/)
const poses=route(input,'taian-nadir-roundtrip-v1',148.5)
assert.strictEqual(poses.length,33)
assert.strictEqual(new Set(poses.map(p=>p.rangeMeters)).size,17)
assert(poses.every(p=>p.headingDegrees===0&&p.tiltDegrees===0&&p.target.heightMeters===148.5))
assert.strictEqual(poses[0].rangeMeters,4*input.radiusMeters)
assert.strictEqual(poses[16].nominalLevel,16)
for(let i=0;i<16;++i)assert.strictEqual(poses[i].rangeMeters,poses[32-i].rangeMeters)
assert.throws(()=>validate({...input,maximumTopologyChanges:64}),/Unsupported/)
assert.throws(()=>validate({...input,maximumManagedBytes:2**30}),/Unsupported/)
assert.throws(()=>route(input,'taian-nadir-roundtrip-v1',NaN),/ground height/)
assert.throws(()=>commandFor({...poses[0],id:'escape\npose'}),/identity/)
assert.throws(()=>commandFor({...poses[0],tiltDegrees:90}),/command/)
const oblique=route(input,'taian-oblique-fixed-v1',148.5)
assert.strictEqual(oblique.length,10)
assert.deepStrictEqual(oblique.slice(0,5).map(p=>p.tiltDegrees),[0,45,76.3,45,0])
const row={id:'sample',status:'ready',threshold:0.01,projection:[1],view:[2],position:[3],
  targetMet:true,allKeys:['0/0/0/0/0'],visibleKeys:['0/0/0/0/0']}
assert(compare(row,row).sameSets)
assert(!compare(row,{...row,visibleKeys:[]}).sameSets)
assert(!compare(row,{...row,targetMet:false}).bothTargetsMet)
assert.throws(()=>compare(row,{...row,view:[4]}),/inputs differ/)
assert.throws(()=>compare(row,{...row,allKeys:row.allKeys.concat(row.allKeys)}),/Duplicate/)
assert(!compare(row,{...row,status:'stalled'}).bothReady)
const check=roundtrip(poses.map(p=>({...row,id:p.id})),poses)
assert.strictEqual(check.length,16)
assert(check.every(c=>c.sameSets))
const pack={fixtureSha256:'base',manifestSha256:'metadata',records:[
  {key:[2,0,-1,2],status:200,bytes:3,sha256:'a'},
  {key:[2,-1,0,2],status:404,bytes:0,sha256:null}]}
assert.strictEqual(datasetIdentity(pack),datasetIdentity({...pack,records:pack.records.slice().reverse()}))
assert.notStrictEqual(datasetIdentity(pack),datasetIdentity({...pack,records:[{...pack.records[0],sha256:'changed'},pack.records[1]]}))
console.log('Headless scheduling cases: fixed 33-stage route, oblique input, precision/budget and comparison guards passed')
