const assert = require('assert')
const { ImageryGroupAdmission } = require('../../sdk/js/imagery/imagery_group_admission')
const { ResourceCache } = require('../../sdk/js/resources/resource_cache')
const { ResourceLedger } = require('../../sdk/js/resources/resource_ledger')
const { ResourceWorkspace } = require('../../sdk/js/resources/resource_workspace')

const ledger = new ResourceLedger(100), disposed = []
const cache = new ResourceCache({ledger, maximumBytes: 80, maximumEntries: 8,
  canEvict: key => key !== 'display', dispose: value => disposed.push(value)})
cache.set('display', 'display', 20)
cache.set('idle', 'idle', 20)
const competing = ledger.reserve('competing', 60)
const groups = new ImageryGroupAdmission(cache)
const wanted = new Map([['a', {}], ['b', {}]])
const beforeProbe = ledger.stats(), beforeCache = cache.stats()
assert.strictEqual(groups.canFitImages(wanted, 20, new Set(), 40), false)
assert(groups.canFitImages(wanted, 20, new Set(), 60), 'A reclaimable idle image was omitted from the lower bound')
assert.strictEqual(cache.maximumBytes, 80, 'A replacement quote changed the steady cache limit')
assert.deepStrictEqual(ledger.stats(), beforeProbe)
assert.deepStrictEqual(cache.stats(), beforeCache)
assert.deepStrictEqual(disposed, [], 'Image feasibility evicted the current cache')
// An image-only fit is not shared credit; the competing owner still prevents
// the real transaction until its actual bytes have been refunded.
assert.strictEqual(groups.admit(wanted, 20, new Set()), false)
assert.deepStrictEqual(disposed, [], 'Rejected group partially evicted the cache')
assert.strictEqual(cache.reservedBytes, 0)
assert(competing.resize(40))
assert(groups.admit(wanted, 20, new Set()))
assert.deepStrictEqual(disposed, ['idle'])
assert.strictEqual(ledger.bytes, 100)
const revision = ledger.revision
assert(groups.admit(wanted, 20, new Set()))
assert.strictEqual(ledger.revision, revision, 'Existing group generated a capacity wake loop')

const active = groups.take('a'), queued = new Map([['b', {}]])
assert(active)
groups.retain(new Set(), queued)
assert.strictEqual(queued.size, 0, 'Cancelled unstarted work remained queued')
assert.strictEqual(groups.pending.size, 0)
assert.strictEqual(cache.reservedBytes, 20, 'Group cancellation refunded active production')
cache.clear({retainReservations: true})
assert.strictEqual(ledger.bytes, 60, 'Source replacement refunded in-flight production')
active.cancel()
competing.release()
assert.strictEqual(ledger.bytes, 0)

// A ready child has its measured GPU size, not a fresh production envelope.
cache.set('b', 'ready', 4)
assert(groups.canFitImages(wanted, 20, new Set(), 24), 'A cached sibling was priced as a new image')
assert.strictEqual(groups.canFitImages(wanted, 20, new Set(), 23), false,
  'The lower bound evicted a sibling needed by the same group')
assert(groups.admit(wanted, 20, new Set()))
assert.strictEqual(cache.bytes + cache.reservedBytes, 24)
assert(groups.take('a').commit('a'))
assert.strictEqual(groups.pending.size, 0)
assert(groups.admit(new Map([['terminal', {}]]), 80, new Set(['terminal'])))
assert.strictEqual(cache.reservedBytes, 0)
cache.clear()
assert.strictEqual(ledger.bytes, 0)
// A header already owns its destination. Its body stage can need additional
// producer workspace even though it requests no new GPU images or UV outputs.
const workspace = new ResourceWorkspace('imagery-production')
assert.strictEqual(groups.admit(new Map(), 20, new Set(), workspace, 101), false,
  'An empty destination group bypassed the shared workspace limit')
assert.strictEqual(ledger.bytes, 0)
assert(groups.admit(new Map(), 20, new Set(), workspace, 100))
assert.strictEqual(workspace.availableBytes, 100)
assert.strictEqual(ledger.bytes, 100)
const body = workspace.take(40)
workspace.retire()
assert.strictEqual(ledger.bytes, 40, 'Retirement refunded an active body loan')
body.release()
assert.strictEqual(ledger.bytes, 0)
console.log('Atomic imagery destination groups, resident reuse and producer-owned cancellation passed')
