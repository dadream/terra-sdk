const assert = require('assert')
const { ResourceCache } = require('../../sdk/js/resources/resource_cache')
const { ResourceLedger } = require('../../sdk/js/resources/resource_ledger')
const { SurfaceHandoff } = require('../../sdk/js/terrain/surface_handoff')

const pins = new Set(['shown']), disposed = []
const cache = new ResourceCache({maximumBytes: 12, maximumEntries: 3,
  canEvict: key => !pins.has(key), dispose: value => disposed.push(value)})
cache.trySet('shown', 'displayed', 6)
cache.trySet('idle', 'evictable', 2)
const first = cache.reserve('fetch-a', 4)
assert(first)
assert.strictEqual(cache.stats().reservedBytes, 4)
assert.strictEqual(cache.has('fetch-a'), false, 'A reservation became presentable content')
assert.strictEqual(cache.reserve('fetch-a', 4), null)
assert.strictEqual(cache.reserve('fetch-b', 4), null, 'Parallel producers overcommitted the same free bytes')
assert(cache.has('idle'), 'Failed reservation evicted only part of the required victims')
assert(first.resize(6), 'An unpinned cached resource could not fund a reservation')
assert.deepStrictEqual(disposed, ['evictable'])
assert.strictEqual(first.resize(7), false, 'A reservation consumed pinned display memory')
assert.strictEqual(cache.stats().reservedBytes, 6)
assert(first.commit('decoded'))
assert.strictEqual(first.commit('duplicate'), false)
assert.strictEqual(first.cancel(), false)
assert.strictEqual(cache.stats().bytes, 12)
assert.strictEqual(cache.stats().reservedBytes, 0)
assert.strictEqual(cache.stats().highWaterBytes, 12)

cache.delete('fetch-a')
const cancelled = cache.reserve('fetch-c', 6)
assert(cancelled.cancel())
assert.strictEqual(cancelled.cancel(), false)
const late = cache.reserve('fetch-c', 6)
cache.clear()
const current = cache.reserve('fetch-c', 6)
assert.strictEqual(late.commit('old source'), false, 'Late completion restored an invalidated source')
assert.strictEqual(late.cancel(), false, 'Old cancellation released another generation\'s lease')
assert.strictEqual(cache.stats().reservedBytes, 6)
assert(current.commit('new source'))
assert.strictEqual(cache.get('fetch-c'), 'new source')

// A smaller budget during resize admits no new work until live owners retire.
pins.add('fetch-c')
cache.maximumBytes = 4
cache.evict()
assert.strictEqual(cache.reserve('extra', 1), null)
assert(cache.has('fetch-c'))
pins.delete('fetch-c')
cache.evict()
assert(cache.reserve('extra', 4).cancel())
assert.throws(() => cache.reserve('bad', Infinity), /safe integer/)
cache.clear()

// GPU uploads keep decoded content charged after source invalidation. A new
// source may reuse the same key, but it cannot reuse bytes still held by work.
const retired = [], heldCache = new ResourceCache({maximumBytes: 12, maximumEntries: 2,
  dispose: value => retired.push(value)})
assert(heldCache.trySet('tile', 'old', 8))
const releaseA = heldCache.retain('tile'), releaseB = heldCache.retain('tile')
assert.strictEqual(heldCache.retain('missing'), null)
assert.strictEqual(heldCache.reserve('too-large', 5), null, 'Admission evicted an uploading image')
heldCache.clear()
assert.strictEqual(heldCache.has('tile'), false)
assert.deepStrictEqual(heldCache.values(), [])
assert.strictEqual(heldCache.stats().retainedEntries, 1)
assert.strictEqual(heldCache.bytes, 8)
assert.deepStrictEqual(retired, [])
assert(heldCache.trySet('tile', 'new', 4))
const releaseNew = heldCache.retain('tile')
assert.strictEqual(heldCache.reserve('extra', 0), null, 'Retired entries escaped the entry budget')
releaseA(); releaseA()
assert.strictEqual(heldCache.bytes, 12)
releaseB(); releaseB()
assert.deepStrictEqual(retired, ['old'])
assert.strictEqual(heldCache.bytes, 4)
assert.strictEqual(heldCache.stats().retainedEntries, 0)
assert.strictEqual(heldCache.get('tile'), 'new', 'Retired release removed a newer source')
const heldRevision = heldCache.revision
releaseNew()
assert(heldCache.revision > heldRevision, 'Waiting admission did not observe an evictable upload completion')
assert.deepStrictEqual(retired, ['old'], 'Resident content was disposed when its upload finished')
assert(heldCache.reserve('extra', 12).cancel(), 'Released resident entry remained unevictable')
assert.deepStrictEqual(retired, ['old', 'new'])
assert.strictEqual(heldCache.stats().highWaterBytes, 12)
heldCache.clear()

// Independent caches cannot each spend the same shared capacity. Reclaim only
// idle entries, and reject a transaction before evicting any partial victim set.
const ledger = new ResourceLedger(12), freed = []
const geometry = new ResourceCache({ledger, owner: 'geometry', maximumBytes: 12,
  canEvict: key => key !== 'shown', dispose: value => freed.push(value)})
const imagery = new ResourceCache({ledger, owner: 'imagery', maximumBytes: 12,
  dispose: value => freed.push(value)})
geometry.trySet('shown', 'shown', 6)
geometry.trySet('idle', 'idle', 2)
imagery.trySet('image', 'image', 4)
const imageHold = imagery.retain('image')
let available = 0
const unsubscribe = ledger.subscribe(() => { ++available })
assert.strictEqual(geometry.reserve('candidate', 5), null)
assert.deepStrictEqual(freed, [])
assert.strictEqual(available, 0, 'Rejected admission signalled freed capacity')
imageHold()
const gpu = geometry.reserve('candidate', 5)
assert(gpu)
assert.deepStrictEqual(freed, ['idle', 'image'])
assert.deepStrictEqual({...ledger.stats().owners}, {
  geometry: {resident: 6, reserved: 5, retired: 0}})
assert.strictEqual(ledger.reserve('output', 2), null)
assert(gpu.commit('candidate'))
const candidateHold = geometry.retain('candidate')
geometry.delete('candidate')
assert.strictEqual(ledger.stats().retiredBytes, 5)
assert.strictEqual(ledger.reserve('output', 2), null, 'Retired held bytes were reused')
candidateHold()
const output = ledger.reserve('output', 6)
assert(output)
const prepared = output.split(4, 'resident')
assert.strictEqual(ledger.bytes, 12, 'Handoff allocated or lost a second charge')
output.release(); output.release()
ledger.setLimit(8)
assert.strictEqual(ledger.stats().overBudgetBytes, 2)
assert(prepared.resize(2), 'Shrinking a lease could not recover from a lowered budget')
assert.strictEqual(ledger.stats().overBudgetBytes, 0)
prepared.release()
geometry.clear(); imagery.clear()
assert.strictEqual(ledger.bytes, 0)
assert.strictEqual(ledger.leases.size, 0)
assert.strictEqual(ledger.highWaterBytes, 12)
unsubscribe()
const beforeUnsubscribed = available
ledger.reserve('late', 1).release()
assert.strictEqual(available, beforeUnsubscribed)

