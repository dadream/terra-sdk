// Encoded recovery grows a resident lease before decode, then shrinks it after
// the GPU receipt. Failure must preserve all candidates and pinned content.
{
  const ledger = new ResourceLedger(16), freed = []
  const cache = new ResourceCache({ledger, maximumBytes: 16, canEvict: key => key !== 'display',
    dispose: value => freed.push(value)})
  cache.trySet('display', 'pixels', 8); cache.trySet('idle', 'idle', 8)
  const entry = cache.entries.get('display'), hold = cache.retain('display')
  assert.strictEqual(cache.resize('display', 17, entry), false)
  assert.deepStrictEqual(freed, [])
  assert.strictEqual(cache.bytes, 16)
  assert(cache.resize('display', 12, entry))
  assert.deepStrictEqual(freed, ['idle'])
  assert.strictEqual(cache.bytes, 12)
  assert.strictEqual(ledger.bytes, 12)
  ledger.setLimit(4); cache.maximumBytes = 4
  assert(cache.resize('display', 6, entry), 'Over-budget ownership cannot shrink')
  assert.strictEqual(ledger.bytes, 6)
  cache.delete('display')
  assert.strictEqual(cache.resize('display', 0, entry), false, 'A retired producer changed its charge')
  hold()
  assert.strictEqual(ledger.bytes, 0)
  assert(cache.trySet('display', 'replacement', 4))
  assert.strictEqual(cache.resize('display', 0, entry), false, 'A stale receipt shrank a newer generation')
  assert.strictEqual(cache.bytes, 4)
  cache.clear()
  assert.strictEqual(ledger.bytes, 0)
}

// Notifications cannot re-enter a half-finished cache transaction. Coalesce
// refunds and remove subscriptions before queued callbacks are delivered.
Promise.resolve().then(async () => {
  const shared = new ResourceLedger(8), cache = new ResourceCache({ledger: shared})
  cache.trySet('old', {}, 8)
  let wakeups = 0, competing
  const stop = shared.subscribe(() => { ++wakeups; competing = shared.reserve('other', 1) })
  const held = cache.reserve('new', 8)
  assert(held)
  assert.strictEqual(wakeups, 0)
  await Promise.resolve()
  assert.strictEqual(wakeups, 1)
  assert.strictEqual(competing, null, 'A wakeup spent capacity already reserved by its triggering transaction')
  stop(); held.cancel(); cache.clear()
  await Promise.resolve()
  assert.strictEqual(wakeups, 1)
}).catch(error => { console.error(error); process.exitCode = 1 })

// Producer and destination must be admitted together, before either allocates.
{
  const {OutputTransaction} = require('../../sdk/js/resources/output_transaction')
  const ledger = new ResourceLedger(100)
  const shown = ledger.reserve('display', 40); shown.mark('resident')
  assert.strictEqual(OutputTransaction.reserve(ledger, 31, 31, 'input', 'gpu'), null)
  assert.strictEqual(ledger.bytes, 40, 'Failed joint admission changed displayed ownership')
  const job = OutputTransaction.reserve(ledger, 30, 30, 'input', 'gpu', [shown])
  assert(job && job.input.bytes === 30 && job.output.bytes === 30)
  assert.strictEqual(ledger.reserve('competitor', 1), null, 'Production lost its destination capacity')
  job.input.mark('resident')
  const failed = job.takeOutput(10)
  job.returnOutput(failed)
  assert.strictEqual(job.output.bytes, 30)
  const submitted = job.takeOutput(12)
  submitted.mark('resident')
  assert(job.input.resize(18))
  assert.strictEqual(ledger.bytes, 88)
  job.retire()
  assert.strictEqual(ledger.stats().retiredBytes, 36)
  job.release(); job.release()
  assert.strictEqual(ledger.bytes, 52, 'Closing production refunded submitted GPU content')
  assert.throws(() => job.takeOutput(1), /closed/)
  submitted.release(); shown.release()
  assert.strictEqual(ledger.bytes, 0)
  const abandoned = OutputTransaction.reserve(ledger, 10, 10, 'input', 'gpu')
  const inFlight = abandoned.takeOutput(10)
  abandoned.release()
  assert.strictEqual(ledger.bytes, 10, 'In-flight output lost ownership before its receipt')
  abandoned.returnOutput(inFlight)
  assert.strictEqual(ledger.bytes, 0)
}
console.log('Producer/destination atomic credit, rollback and in-flight receipts passed')

// A complete destination group and its producer share one admission. Reused
// destinations cannot become eviction victims during that producer's work.
{
  const ledger = new ResourceLedger(35)
  const cache = new ResourceCache({ledger, owner: 'gpu', maximumBytes: 24,
    canEvict: key => key !== 'display'})
  for (const key of ['display', 'reused', 'idle']) assert(cache.trySet(key, key, 6))
  const requests = new Map([['reused', 6], ['a', 6], ['b', 6]])
  const before = ledger.stats(), order = cache.values()
  assert.strictEqual(cache.canReserveBatch(requests, 12), false)
  assert.deepStrictEqual(ledger.stats(), before)
  assert.deepStrictEqual(cache.values(), order)
  assert.strictEqual(cache.reserveBatch(requests, 12, 'producer'), null)
  assert.deepStrictEqual(cache.values(), ['display','reused','idle'], 'Failed group admission evicted partial victims')
  assert.strictEqual(cache.reservedBytes, 0)
  ledger.setLimit(36)
  const feasible = ledger.stats()
  assert(cache.canReserveBatch(requests, 12))
  assert.deepStrictEqual(ledger.stats(), feasible, 'Feasibility spent output credit or evicted its victims')
  assert.deepStrictEqual(cache.values(), order)
  assert.strictEqual(cache.entries.get('reused').holds, undefined, 'Feasibility leaked a destination borrow')
  const group = cache.reserveBatch(requests, 12, 'producer')
  assert(group && group.valid())
  assert.strictEqual(group.credit.bytes, 12)
  assert.strictEqual(cache.reservedBytes, 12)
  assert(!cache.has('idle') && cache.has('reused'))
  assert.strictEqual(ledger.reserve('competitor', 1), null)
  const pending = group.take('a')
  group.release(); group.release(); group.credit.release()
  assert.strictEqual(ledger.bytes, 18, 'Closing the producer refunded a claimed upload')
  assert(pending.valid() && pending.commit('a'))
  assert.strictEqual(cache.reservedBytes, 0)
  cache.clear(); assert.strictEqual(ledger.bytes, 0)
  const invalidated = cache.reserveBatch(new Map([['a', 6]]), 12, 'producer')
  cache.clear()
  assert(!invalidated.valid(), 'Context invalidation left a stale destination grant valid')
  assert.strictEqual(ledger.bytes, 12, 'Context loss refunded CPU work before it completed')
  invalidated.release(); invalidated.credit.release()
  assert.strictEqual(ledger.bytes, 0)
}
console.log('Atomic cache group admission, reused destinations and producer ownership passed')

// A later immutable plan borrows an existing upload rather than reserving its
// bytes twice. Completion transfers that borrow to a resident hold atomically.
for (const outcome of ['commit', 'cancel', 'clear', 'release', 'resize']) {
  const ledger = new ResourceLedger(18), disposed = []
  const cache = new ResourceCache({ledger, maximumBytes: 12, dispose: value => disposed.push(value)})
  const upload = cache.reserve('shared', 6)
  const requests = new Map([['shared', 6], ['new', 6]])
  assert(cache.canReserveBatch(requests, 6))
  assert.strictEqual(cache.reservations.get('shared').borrowers.size, 0)
  assert.strictEqual(ledger.bytes, 6)
  assert.throws(() => cache.reserveBatch(new Map([['shared', 5]]), 0, 'producer'), /size changed/)
  const group = cache.reserveBatch(requests, 6, 'producer')
  assert(group && group.valid(), 'Existing production was mistaken for occupied capacity')
  assert.strictEqual(group.take('shared'), undefined, 'A borrower became a second GPU producer')
  assert.strictEqual(ledger.bytes, 18)
  if (outcome === 'commit') {
    assert(upload.commit('shared'))
    assert(group.valid(), 'Completing an upload invalidated the prepared successor')
    assert.strictEqual(ledger.reserve('competitor', 1), null, 'Completion lost the successor destination hold')
    cache.delete('shared')
    assert(!group.valid(), 'Source invalidation kept a borrowed destination valid')
    assert.strictEqual(ledger.bytes, 18, 'Invalidation refunded a borrowed resident before its release')
    assert.deepStrictEqual(disposed, [])
  } else if (outcome === 'cancel') {
    upload.cancel()
    assert(!group.valid(), 'Cancelled production left a valid destination')
    const replacement = cache.reserve('shared', 6)
    assert(replacement && !group.valid(), 'Reusing a key resurrected the cancelled borrow')
    replacement.cancel()
  } else if (outcome === 'clear') {
    cache.clear()
    assert(!group.valid())
    assert.strictEqual(ledger.bytes, 6, 'Cache clearing refunded unrelated CPU production')
  } else if (outcome === 'resize') {
    assert(upload.resize(5))
    assert(!group.valid(), 'Changing immutable output size preserved admission')
    upload.cancel()
  }
  group.release(); group.release(); group.credit.release()
  if (outcome === 'release') {
    assert(upload.valid(), 'Cancelling a successor cancelled the original producer')
    assert.strictEqual(ledger.bytes, 6)
    upload.commit('shared')
    const other = ledger.reserve('competitor', 18)
    assert(other, 'An abandoned borrow pinned the completed resource')
    other.release()
  }
  cache.clear()
  assert.strictEqual(ledger.bytes, 0)
}
console.log('Shared immutable destinations, completion holds, cancellation and invalidation passed')
